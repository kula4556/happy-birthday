function renderStory() {
  const story = C.stories[storyIndex],
    slide = story.slides[storySlideIndex];
  storyTitle.textContent = story.title;
  if (isLaoText(story.title)) storyTitle.setAttribute("lang", "lo");
  else storyTitle.removeAttribute("lang");
  storyText.textContent = slide.text;
  if (isLaoText(slide.text)) storyText.setAttribute("lang", "lo");
  else storyText.removeAttribute("lang");
  storyImage.hidden = !slide.img;
  if (slide.img) {
    storyImage.src = slide.img;
    storyImage.alt = story.title;
  } else {
    storyImage.removeAttribute("src");
    storyImage.alt = "";
  }
  storyProgress.innerHTML = story.slides
    .map((_, i) => `<span class="${i < storySlideIndex ? "done" : i === storySlideIndex ? "current" : ""}"></span>`)
    .join("");
  storyCount.textContent = `${storySlideIndex + 1} / ${story.slides.length}`;
  storyPrev.disabled = storyIndex === 0 && storySlideIndex === 0;
  const isLastStorySlide =
    storyIndex === C.stories.length - 1 && storySlideIndex === story.slides.length - 1;
  storyNext.textContent = isLastStorySlide ? "ຈົບ" : "ຕໍ່ໄປ";
  storyNext.setAttribute(
    "aria-label",
    isLastStorySlide ? "ຈົບເລື່ອງ" : "ສະໄລ້ຕໍ່ໄປ",
  );
}
function openStory(index, trigger) {
  storyIndex = index;
  storySlideIndex = 0;
  storyReturnFocus = trigger;
  renderStory();
  storyDialog.showModal();
  storyClose.focus();
}
function moveStory(direction) {
  const story = C.stories[storyIndex];
  if (direction > 0 && storySlideIndex === story.slides.length - 1) {
    if (storyIndex === C.stories.length - 1) {
      storyDialog.close();
      return;
    }
    storyIndex++;
    storySlideIndex = 0;
  } else if (direction < 0 && storySlideIndex === 0) {
    if (storyIndex === 0) return;
    storyIndex--;
    storySlideIndex = C.stories[storyIndex].slides.length - 1;
  } else {
    storySlideIndex += direction;
  }
  renderStory();
}

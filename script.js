function confetti(n = 140, x = 0.5, y = 0.55) {
  if (RM) n = Math.min(n, 30);
  const col = [
    "#f9a8c9",
    "#ffd6e8",
    "#c9b1ff",
    "#ffe9a8",
    "#ffffff",
    "#ff8fbd",
  ];
  for (let i = 0; i < n; i++) {
    const a = Math.random() * 9.28,
      v = 4 + Math.random() * 9;
    ps.push({
      x: x * cv.width,
      y: y * cv.height,
      vx: Math.cos(a) * v,
      vy: Math.sin(a) * v - 6,
      s: 5 + Math.random() * 6,
      r: Math.random() * 6,
      vr: (Math.random() - 0.5) * 0.3,
      c: col[i % 6],
    });
  }
  if (!raf) raf = requestAnimationFrame(loop);
}
function loop() {
  cx.clearRect(0, 0, cv.width, cv.height);
  ps = ps.filter((p) => p.y < cv.height + 20);
  for (const p of ps) {
    p.vy += 0.25;
    p.vx *= 0.99;
    p.x += p.vx;
    p.y += p.vy;
    p.r += p.vr;
    cx.save();
    cx.translate(p.x, p.y);
    cx.rotate(p.r);
    cx.fillStyle = p.c;
    cx.fillRect(-p.s / 2, -p.s / 3, p.s, p.s * 0.6);
    cx.restore();
  }
  raf = ps.length ? requestAnimationFrame(loop) : 0;
}

